#!/usr/bin/env python3
"""Profile the selected support-ticket dataset and write a report.

Re-run from the repository root:

    .venv/bin/python assignment1/task2/profile_dataset.py
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent
REPO_ROOT = ROOT.parent.parent
SOURCE_CSV = (
    REPO_ROOT
    / "assignment1"
    / "task1"
    / "dataset_samples"
    / "candidate1_aa_dataset-tickets-multi-lang-5-2-50-version.csv"
)
OUTPUT_DIR = ROOT / "outputs"
REPORT_PATH = OUTPUT_DIR / "profile_report.md"
INSPECTION_PATH = OUTPUT_DIR / "inspection_sample.csv"

TICKET_TEXT_FIELDS = ("subject", "body")
ROUTING_LABEL_FIELD = "queue"
LANGUAGE_FIELD = "language"
ENGLISH_VALUE = "en"
SHORT_TEXT_THRESHOLD = 80
RELEVANT_FIELDS = [
    "subject",
    "body",
    "answer",
    "type",
    "queue",
    "priority",
    "language",
    "version",
    "tag_1",
    "tag_2",
    "tag_3",
    "tag_4",
    "tag_5",
    "tag_6",
    "tag_7",
    "tag_8",
]


def ticket_text(frame: pd.DataFrame) -> pd.Series:
    subject = frame["subject"].fillna("").astype(str)
    body = frame["body"].fillna("").astype(str)
    return (subject + "\n" + body).str.strip()


def add_record_id(frame: pd.DataFrame) -> pd.DataFrame:
    out = frame.copy()
    out["record_id"] = [f"src-{i:05d}" for i in range(len(out))]
    return out


def missing_table(frame: pd.DataFrame) -> pd.DataFrame:
    counts = frame[RELEVANT_FIELDS].isna().sum()
    n = len(frame)
    return pd.DataFrame(
        {
            "field": counts.index,
            "missing_count": counts.to_numpy(),
            "missing_proportion": (counts / n).to_numpy(),
        }
    )


def label_table(frame: pd.DataFrame) -> pd.DataFrame:
    counts = frame[ROUTING_LABEL_FIELD].value_counts(dropna=False).sort_index()
    n = len(frame)
    return pd.DataFrame(
        {
            "queue": counts.index.astype(str),
            "count": counts.to_numpy(),
            "proportion": (counts / n).to_numpy(),
        }
    )


def md_table(df: pd.DataFrame, float_cols: list[str] | None = None) -> str:
    float_cols = float_cols or []
    headers = list(df.columns)
    lines = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    for _, row in df.iterrows():
        cells = []
        for col in headers:
            value = row[col]
            if col in float_cols:
                cells.append(f"{float(value):.4f}")
            else:
                cells.append(str(value))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def select_inspection_sample(english: pd.DataFrame) -> pd.DataFrame:
    """Stratified systematic sample: two English records per queue.

    Strata are routing queues. Within each stratum, rows are ordered by
    record_id and the 25th and 75th percentile positions are taken. This is
    representative (every class appears) and not random or targeted.
    """
    parts = []
    for _, group in english.groupby(ROUTING_LABEL_FIELD, sort=True):
        ordered = group.sort_values("record_id")
        n = len(ordered)
        idx_low = int((n - 1) * 0.25)
        idx_high = int((n - 1) * 0.75)
        parts.append(ordered.iloc[[idx_low, idx_high]])
    sample = pd.concat(parts, ignore_index=True)
    return sample.sort_values(["queue", "record_id"]).reset_index(drop=True)


def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    raw = pd.read_csv(SOURCE_CSV)
    df = add_record_id(raw)
    df["ticket_text"] = ticket_text(df)
    df["ticket_text_length"] = df["ticket_text"].str.len()

    english = df[df[LANGUAGE_FIELD].astype(str).str.lower() == ENGLISH_VALUE].copy()
    english_lengths = english["ticket_text_length"]
    short = english[english["ticket_text_length"] < SHORT_TEXT_THRESHOLD].sort_values(
        "ticket_text_length"
    )
    duplicate_count = int(english["ticket_text"].duplicated().sum())

    length_summary = english_lengths.describe()
    shortest = english.nsmallest(10, "ticket_text_length")[
        ["record_id", "queue", "priority", "ticket_text_length", "ticket_text"]
    ]

    inspection = select_inspection_sample(english)
    inspection.to_csv(INSPECTION_PATH, index=False)

    missing_all = missing_table(df)
    missing_en = missing_table(english)
    labels_en = label_table(english)

    report = f"""# Dataset profile report

Source file: `{SOURCE_CSV.relative_to(REPO_ROOT)}`
Generated by: `assignment1/task2/profile_dataset.py`

## Totals

- Total records: {len(df)}
- Total columns: {raw.shape[1]}
- Records after English filter (`{LANGUAGE_FIELD}` == `{ENGLISH_VALUE}`): {len(english)}
- Derived columns used only in this report: `record_id`, `ticket_text`, `ticket_text_length`

## Record grain

One row is one customer-support email ticket: a subject line (sometimes missing), a message body, an agent answer, a routing queue, and related metadata (type, priority, language, version, tags).

## Ticket-text and routing-label fields

- Ticket text: `{TICKET_TEXT_FIELDS[0]}` and `{TICKET_TEXT_FIELDS[1]}` concatenated as `strip(subject + newline + body)`, with missing subject treated as empty.
- Routing label: `{ROUTING_LABEL_FIELD}`
- Stable identifier: `record_id` = `src-{{zero-padded 0-based row index in the source CSV}}`

## Missing values (full source file, n={len(df)})

{md_table(missing_all, float_cols=["missing_proportion"])}

## Missing values (English subset, n={len(english)})

{md_table(missing_en, float_cols=["missing_proportion"])}

## Routing-label counts and proportions (English subset)

{md_table(labels_en, float_cols=["proportion"])}

## Ticket-text length summary (English subset, characters)

- count: {int(length_summary["count"])}
- mean: {length_summary["mean"]:.2f}
- std: {length_summary["std"]:.2f}
- min: {int(length_summary["min"])}
- 25%: {length_summary["25%"]:.2f}
- 50%: {length_summary["50%"]:.2f}
- 75%: {length_summary["75%"]:.2f}
- max: {int(length_summary["max"])}

Suspiciously short threshold: combined ticket text shorter than {SHORT_TEXT_THRESHOLD} characters.

- Number of English records below threshold: {len(short)}
- Proportion of English records below threshold: {len(short) / len(english):.4f}

### Ten shortest English ticket texts

{md_table(
        shortest.assign(
            ticket_text=shortest["ticket_text"]
            .str.replace("\n", " / ", regex=False)
            .str.replace("|", "/", regex=False)
        )
    )}

## Exact duplicate ticket texts (English subset)

- Exact duplicate count (rows whose ticket text already appeared earlier): {duplicate_count}
- Unique English ticket texts: {english["ticket_text"].nunique()}
"""

    REPORT_PATH.write_text(report, encoding="utf-8")
    print(f"Wrote {REPORT_PATH}")
    print(f"Wrote {INSPECTION_PATH} ({len(inspection)} records)")


if __name__ == "__main__":
    main()
